document.addEventListener(

    "contextmenu",

    function(
        event
    ) {

        event.preventDefault();
    }
);


document.addEventListener(

    "keydown",

    function(
        event
    ) {

        if (
            event.key ===
            "F12"
        ) {

            event.preventDefault();
        }


        if (
            event.ctrlKey

            &&

            event.shiftKey

            &&

            [
                "I",
                "J",
                "C"
            ].includes(
                event.key.toUpperCase()
            )
        ) {

            event.preventDefault();
        }


        if (
            event.ctrlKey

            &&

            event.key.toUpperCase() ===
            "U"
        ) {

            event.preventDefault();
        }
    }
);
