let alertCallback = null;


window.showAlert = function(
    title,
    message,
    icon = "👨‍💻",
    callback = null
) {

    const modal =
        document.getElementById(
            "custom-alert"
        );


    if (
        !modal
    ) {

        window.alert(
            title +
            "\n\n" +
            message
        );


        if (
            callback
        ) {

            callback();
        }


        return;
    }


    setText(
        "alert-title",
        title
    );


    setText(
        "alert-icon",
        icon
    );


    const messageBox =
        document.getElementById(
            "alert-message"
        );


    if (
        messageBox
    ) {

        messageBox.innerHTML =
            String(
                message
            )
                .replace(
                    /\n/g,
                    "<br>"
                );
    }


    modal.classList.remove(
        "hidden"
    );


    alertCallback =
        callback;
};


window.closeAlert = function() {

    const modal =
        document.getElementById(
            "custom-alert"
        );


    if (
        modal
    ) {

        modal.classList.add(
            "hidden"
        );
    }


    if (
        alertCallback
    ) {

        const callback =
            alertCallback;


        alertCallback =
            null;


        callback();
    }
};


