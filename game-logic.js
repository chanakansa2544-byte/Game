/* =========================================================
   PENALTY / SHIELD
========================================================= */

function applyPenalty(
    goldPenalty,
    energyPenalty
) {

    if (
        shields >
        0
    ) {

        shields--;


        logCMD(

            "INSURANCE SHIELD ABSORBED PENALTY",

            "warn"
        );


        return;
    }


    gold =
        Math.max(

            0,

            gold -
            goldPenalty
        );


    energy =
        Math.max(

            0,

            energy -
            energyPenalty
        );
}


