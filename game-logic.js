/* =========================================================
   USE DIAGNOSTIC TOOL
========================================================= */

window.useTool = function(
    toolType
) {

    if (
        !currentCaseData
    ) {

        return;
    }


    if (
        currentStage !==
        "diagnosis"
    ) {

        showAlert(

            "อยู่ในขั้นตอนการแก้ไข",

            "ขณะนี้การวินิจฉัยเสร็จแล้ว กรุณาเลือกขั้นตอนแก้ไข",

            "🛠️"
        );


        return;
    }


    if (
        caseAnswered
    ) {

        return;
    }


    if (
        toolCooldown
    ) {

        logCMD(

            "WAIT: READ PREVIOUS DIAGNOSTIC RESULT",

            "warn"
        );


        return;
    }


    if (
        usedTools.has(
            toolType
        )
    ) {

        showAlert(

            "ตรวจแล้ว",

            "เครื่องมือนี้ถูกใช้ในเคสปัจจุบันแล้ว\nการกดซ้ำไม่ให้ข้อมูลใหม่",

            "🔎"
        );


        return;
    }


    if (
        energy <
        TOOL_COST
    ) {

        showAlert(

            "Energy ไม่เพียงพอ",

            "พลังงานสำหรับการตรวจไม่เพียงพอ\nสามารถใช้ Energy Drink จากคลังอุปกรณ์ได้",

            "🔋"
        );


        return;
    }


    energy -=
        TOOL_COST;


    usedTools.add(
        toolType
    );


    toolCooldown =
        true;


    setTimeout(

        function() {

            toolCooldown =
                false;
        },

        900
    );


    logCMD(

        `RUN TOOL: ${toolType.toUpperCase()}`
    );


    const customEvidence =
        currentCaseData
            .evidence[
                toolType
            ];


    const result =

        customEvidence

        ||

        getDefaultEvidence(

            toolType,

            currentCaseData.state
        );


    const clue =
        document.getElementById(
            "clue-display"
        );


    if (
        clue
    ) {

        clue.innerText =
            result;


        clue.classList.add(
            "active"
        );
    }


    /*
        ไม่บอกเด็กว่า
        "เครื่องมือนี้ถูก"

        เพียงแสดงข้อมูล
        แล้วให้วิเคราะห์เอง
    */

    logCMD(
        result
    );


    updateUI();

    updateAnalysisStatus();

    updateAnswerLocks();
};


/* =========================================================
   SUBMIT ANSWER
========================================================= */

function submitAnswer(
    selected,
    questionObject,
    button
) {

    if (
        caseAnswered
    ) {

        return;
    }


    if (
        currentStage ===
        "diagnosis"

        &&

        !hasEnoughEvidence()
    ) {

        showAlert(

            "หลักฐานยังไม่เพียงพอ",

            "ยังมีข้อมูลสำคัญที่ไม่ได้ตรวจ\nกรุณาใช้เครื่องมือวิเคราะห์เพิ่มเติมก่อนตอบ",

            "🔒"
        );


        return;
    }


    caseAnswered =
        true;


    totalAttempts++;


    disableAllAnswers();


    const isCorrect =
        selected ===
        questionObject.correct;


    if (
        isCorrect
    ) {

        correctAttempts++;


        button.classList.add(
            "btn-success"
        );


        logCMD(

            `DECISION CORRECT: ${selected}`,

            "success"
        );


        logCMD(

            `ACCURACY: ${getAccuracy()}%`,

            "success"
        );


        updateUI();

        syncLeaderboard();


        if (
            currentStage ===
            "diagnosis"
        ) {

            currentCaseDiagnosisCorrect =
                true;


            setTimeout(

                function() {

                    showDiagnosisSuccess(
                        questionObject
                    );

                },

                350
            );


            return;
        }


        finishCorrectCase(
            questionObject
        );


        return;
    }


    button.classList.add(
        "btn-danger"
    );


    logCMD(

        `INCORRECT DECISION: ${selected}`,

        "error"
    );


    if (
        currentStage ===
        "diagnosis"
    ) {

        failDiagnosis(
            questionObject
        );

    } else {

        failAction(
            questionObject
        );
    }
}


